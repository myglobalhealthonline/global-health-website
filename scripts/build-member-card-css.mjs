#!/usr/bin/env node
/**
 * Copy the membership-card CSS out of the frontend's `portal.css` and into
 * `backend/assets/member-card.css`.
 *
 * The card is authored ONCE, in portal.css, between the `card-image:start` and
 * `card-image:end` markers. The backend renders the downloadable PNG and the
 * emailed card with that same CSS, so the image a member saves is the face they
 * saw on the site. The two services deploy standalone, hence a committed copy
 * rather than a cross-package import.
 *
 *   node scripts/build-member-card-css.mjs           # write the copy
 *   node scripts/build-member-card-css.mjs --check   # fail if it has drifted
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(root, "frontend", "app", "portal.css");
const TARGET = path.join(root, "backend", "assets", "member-card.css");

const css = fs.readFileSync(SOURCE, "utf8");
const start = css.indexOf("/* card-image:start");
const end = css.indexOf("/* card-image:end */");
if (start === -1 || end === -1 || end < start) {
  console.error("card-image markers missing from portal.css — see this script's header.");
  process.exit(1);
}

const block = css.slice(css.indexOf("*/", start) + 2, end).trim();
const output = `/* GENERATED by scripts/build-member-card-css.mjs — DO NOT EDIT.
   Source of truth: frontend/app/portal.css, between the card-image markers. */\n\n${block}\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8") : "";
  if (current !== output) {
    console.error(
      "backend/assets/member-card.css is stale — run `node scripts/build-member-card-css.mjs`.",
    );
    process.exit(1);
  }
  console.log("member-card.css is in sync");
} else {
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, output);
  console.log(`wrote ${path.relative(root, TARGET)} (${output.length} bytes)`);
}
